# so far we have only used bianry operators. They expect two arguments.
# now we will use comparison operators. They expect two arguments and return a boolean value.
# == is equal to
# != is not equal to
# > is greater than
# < is less than
# >= is greater than or equal to
# <= is less than or equal to

# Examples:
print(1 == 1) # True
print(1 != 1) # False
print(1 > 1) # False
print(1 < 1) # False
print(1 >= 1) # True
print(1 <= 1) # True

# Comparison operators can be used to compare strings
print("hello" == "hello") # True
print("hello" != "hello") # False