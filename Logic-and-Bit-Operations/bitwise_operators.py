# bitwise operators are used to perform operations on binary numbers
# & operator performs bitwise AND operation
# | operator performs bitwise OR operation
# ^ operator performs bitwise XOR operation
# ~ operator performs bitwise NOT operation
# << operator performs bitwise left shift operation
# >> operator performs bitwise right shift operation

# 15 & 22
# 15 in binary is 1111 and 22 in binary is 10110

print(bin(15))
print(bin(22))

print(15 & 22)

print(15 | 22)

print(15 ^ 22)

print(~15)

print(15 << 2)

print(15 >> 2)

print(5 ^ 11)